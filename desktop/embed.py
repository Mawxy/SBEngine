"""Turn the built GUI page into a C++ header for the desktop app.

usage: python desktop/embed.py gui/spectacular-bid.html desktop/gui_html.h
"""
import pathlib, sys
data = pathlib.Path(sys.argv[1]).read_bytes()
lines = []
for i in range(0, len(data), 24):
    lines.append(",".join(str(b) for b in data[i:i + 24]))
out = ("// Generated by desktop/embed.py from the GUI page. Do not edit.\n#pragma once\n"
       f"static const unsigned long kGuiHtmlLen = {len(data)}UL;\n"
       "static const unsigned char kGuiHtml[] = {\n" + ",\n".join(lines) + "\n};\n")
pathlib.Path(sys.argv[2]).write_text(out)
print(f"wrote {sys.argv[2]} ({len(data) // 1024} KB page)")
