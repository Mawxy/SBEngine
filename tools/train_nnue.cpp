// Trains the NNUE evaluation network from gendata output.
//
//   train_nnue <out.bin> <data.bin> [data2.bin ...] [--epochs N] [--lambda L] [--lr R] [--cpp src/nnue_weights.cpp]
//
// Target = lambda * search label + (1 - lambda) * actual outcome (chips, side to move),
// the same blend Stockfish uses between search scores and game results.
// Plain minibatch Adam on mean squared error; 5% of positions are held out to report
// accuracy against the classic hand-written evaluation.

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <random>
#include <string>
#include <vector>

#include "../src/nnue.h"

using namespace sb;

namespace {

struct Sample {
    uint8_t n;
    uint8_t idx[kNNMaxActive];
    float search, outcome;
};

bool read_data(const std::string& path, std::vector<Sample>& out) {
    FILE* f = std::fopen(path.c_str(), "rb");
    if (!f) return false;
    for (;;) {
        Sample s;
        if (std::fread(&s.n, 1, 1, f) != 1) break;
        if (s.n > kNNMaxActive || std::fread(s.idx, 1, s.n, f) != s.n) break;
        float v[2];
        if (std::fread(v, sizeof v, 1, f) != 1) break;
        s.search = v[0];
        s.outcome = v[1];
        out.push_back(s);
    }
    std::fclose(f);
    return true;
}

// Classic evaluation (chips) recovered from the inputs, for comparison.
float classic(const Sample& s) {
    int pips_me = 0, pips_opp = 0, n_me = 0, n_opp = 0;
    for (int i = 0; i < s.n; ++i) {
        const int x = s.idx[i];
        if (x < 28) { pips_me += tile_pips(x); ++n_me; }
        else if (x < 56) { pips_opp += tile_pips(x - 28); ++n_opp; }
    }
    return (8 * (pips_opp - pips_me) + 40 * (n_opp - n_me)) / 100.0f;
}

struct Adam {
    std::vector<float> m, v;
    float b1 = 0.9f, b2 = 0.999f, eps = 1e-8f;
    long long t = 0;
    explicit Adam(size_t n) : m(n, 0), v(n, 0) {}
    void step(float* p, const float* g, size_t n, float lr) {
        const float c1 = 1 - std::pow(b1, static_cast<float>(t)), c2 = 1 - std::pow(b2, static_cast<float>(t));
        for (size_t i = 0; i < n; ++i) {
            m[i] = b1 * m[i] + (1 - b1) * g[i];
            v[i] = b2 * v[i] + (1 - b2) * g[i] * g[i];
            p[i] -= lr * (m[i] / c1) / (std::sqrt(v[i] / c2) + eps);
        }
    }
};

void write_cpp(const NNWeights& w, const std::string& path, const std::string& note) {
    FILE* f = std::fopen(path.c_str(), "w");
    const float* p = reinterpret_cast<const float*>(&w);
    const size_t n = sizeof(NNWeights) / sizeof(float);
    std::fprintf(f, "// Generated by tools/train_nnue. %s\n#include \"nnue.h\"\nnamespace sb {\nnamespace {\n", note.c_str());
    std::fprintf(f, "alignas(64) const float kData[%zu] = {\n", n);
    for (size_t i = 0; i < n; ++i) std::fprintf(f, "%.7g%s", p[i], (i + 1) % 8 == 0 ? ",\n" : ",");
    std::fprintf(f, "};\n}  // namespace\nconst NNWeights* nn_builtin() { return reinterpret_cast<const NNWeights*>(kData); }\n}  // namespace sb\n");
    std::fclose(f);
}

}  // namespace

int main(int argc, char** argv) {
    std::string out_path, cpp_path;
    std::vector<std::string> data;
    int epochs = 12;
    float lambda = 0.75f, lr0 = 1e-3f;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--epochs") epochs = std::atoi(argv[++i]);
        else if (a == "--lambda") lambda = std::strtof(argv[++i], nullptr);
        else if (a == "--lr") lr0 = std::strtof(argv[++i], nullptr);
        else if (a == "--cpp") cpp_path = argv[++i];
        else if (out_path.empty()) out_path = a;
        else data.push_back(a);
    }
    if (out_path.empty() || data.empty()) {
        std::fprintf(stderr, "usage: train_nnue <out.bin> <data.bin>... [--epochs N] [--lambda L] [--lr R] [--cpp file]\n");
        return 1;
    }
    std::vector<Sample> all;
    for (const auto& d : data)
        if (!read_data(d, all)) std::fprintf(stderr, "cannot read %s\n", d.c_str());
    std::mt19937_64 rng(12345);
    std::shuffle(all.begin(), all.end(), rng);
    const size_t n_val = std::max<size_t>(1000, all.size() / 20);
    std::vector<Sample> val(all.begin(), all.begin() + n_val), train(all.begin() + n_val, all.end());
    std::printf("%zu training positions, %zu held out\n", train.size(), val.size());
    auto target = [&](const Sample& s) { return lambda * s.search + (1 - lambda) * s.outcome; };

    // Init.
    static NNWeights w, gw;
    std::normal_distribution<float> nd(0.0f, 1.0f);
    for (auto& row : w.w1) for (float& x : row) x = nd(rng) * 0.08f;
    for (float& x : w.b1) x = 0.5f;
    for (auto& row : w.w2) for (float& x : row) x = nd(rng) * (1.0f / std::sqrt(static_cast<float>(kNNH1)));
    for (float& x : w.b2) x = 0.5f;
    for (float& x : w.w3) x = nd(rng) * 1.0f;
    double mean = 0;
    for (const auto& s : train) mean += target(s);
    w.b3 = static_cast<float>(mean / train.size());

    const size_t P = sizeof(NNWeights) / sizeof(float);
    Adam adam(P);
    auto eval_set = [&](const std::vector<Sample>& set, double& mse_net, double& mse_classic, double& mse_search) {
        mse_net = mse_classic = mse_search = 0;
        for (const auto& s : set) {
            int idx[kNNMaxActive];
            for (int i = 0; i < s.n; ++i) idx[i] = s.idx[i];
            const double t = target(s);
            const double y = nn_eval(w, idx, s.n);
            mse_net += (y - t) * (y - t);
            mse_classic += (classic(s) - t) * (classic(s) - t);
            mse_search += (s.search - s.outcome) * (s.search - s.outcome);
        }
        mse_net /= set.size(); mse_classic /= set.size(); mse_search /= set.size();
    };
    double vn, vc, vs;
    eval_set(val, vn, vc, vs);
    double var = 0, vm = 0;
    for (const auto& s : val) vm += target(s);
    vm /= val.size();
    for (const auto& s : val) var += (target(s) - vm) * (target(s) - vm);
    var /= val.size();
    std::printf("held-out MSE (chips^2): predict-the-mean %.3f, classic eval %.3f, untrained net %.3f\n", var, vc, vn);

    const int B = 256;
    float h1[B][kNNH1], a1[B][kNNH1], h2[B][kNNH2], a2[B][kNNH2];
    for (int ep = 0; ep < epochs; ++ep) {
        std::shuffle(train.begin(), train.end(), rng);
        const float lr = lr0 * (ep < epochs * 2 / 3 ? 1.0f : 0.3f);
        double loss = 0;
        for (size_t start = 0; start + B <= train.size(); start += B) {
            std::memset(&gw, 0, sizeof gw);
            for (int b = 0; b < B; ++b) {
                const Sample& s = train[start + b];
                for (int k = 0; k < kNNH1; ++k) a1[b][k] = w.b1[k];
                for (int i = 0; i < s.n; ++i)
                    for (int k = 0; k < kNNH1; ++k) a1[b][k] += w.w1[s.idx[i]][k];
                for (int k = 0; k < kNNH1; ++k) h1[b][k] = std::min(std::max(a1[b][k], 0.0f), 1.0f);
                for (int j = 0; j < kNNH2; ++j) a2[b][j] = w.b2[j];
                for (int k = 0; k < kNNH1; ++k)
                    for (int j = 0; j < kNNH2; ++j) a2[b][j] += h1[b][k] * w.w2[k][j];
                float y = w.b3;
                for (int j = 0; j < kNNH2; ++j) {
                    h2[b][j] = std::min(std::max(a2[b][j], 0.0f), 1.0f);
                    y += w.w3[j] * h2[b][j];
                }
                const float err = y - target(s);
                loss += err * err;
                const float dy = 2 * err / B;
                gw.b3 += dy;
                float da2[kNNH2];
                for (int j = 0; j < kNNH2; ++j) {
                    gw.w3[j] += dy * h2[b][j];
                    da2[j] = (a2[b][j] > 0 && a2[b][j] < 1) ? dy * w.w3[j] : 0.0f;
                    gw.b2[j] += da2[j];
                }
                float da1[kNNH1];
                for (int k = 0; k < kNNH1; ++k) {
                    float d = 0;
                    for (int j = 0; j < kNNH2; ++j) {
                        gw.w2[k][j] += h1[b][k] * da2[j];
                        d += w.w2[k][j] * da2[j];
                    }
                    da1[k] = (a1[b][k] > 0 && a1[b][k] < 1) ? d : 0.0f;
                    gw.b1[k] += da1[k];
                }
                for (int i = 0; i < s.n; ++i)
                    for (int k = 0; k < kNNH1; ++k) gw.w1[s.idx[i]][k] += da1[k];
            }
            ++adam.t;
            adam.step(reinterpret_cast<float*>(&w), reinterpret_cast<const float*>(&gw), P, lr);
        }
        eval_set(val, vn, vc, vs);
        std::printf("epoch %2d  train MSE %.3f  held-out MSE %.3f (classic %.3f)\n", ep + 1, loss / (train.size() / B * B), vn, vc);
        std::fflush(stdout);
    }
    nn_save(w, out_path);
    if (!cpp_path.empty()) {
        char note[200];
        std::snprintf(note, sizeof note, "%zu positions, %d epochs, lambda %.2f, held-out MSE %.3f vs classic %.3f.", all.size(), epochs, lambda, vn, vc);
        write_cpp(w, cpp_path, note);
    }
    std::printf("saved %s\n", out_path.c_str());
}
